@dataclass(frozen=True)
class Muscle:
    key: str
    label: str
    group: str  # Push | Shoulders | Pull | Arms | Core | Legs (personal recovery factor groups)
    half_life_h: float
    weekly_low: float
    weekly_high: float
    capacity_es: float  # C_m: fatigue at which readiness hits 0 (10 large, 8 small)
    map_slug: str  # region id in the body map (v8: the muscle key itself)
    region: str = ""
    parent: str = ""  # the muscle a head belongs to ("Pectoralis major"), "" for none
    legacy: str = ""
    deep: bool = False  # hidden under other muscles: drawn in the map's deep layer
    readiness_only: bool = False


def _m(
    key: str,
    label: str,
    region: str,
    group: str,
    half_life_h: float,
    weekly_low: float,
    weekly_high: float,
    capacity_es: float,
    *,
    parent: str = "",
    legacy: str = "",
    deep: bool = False,
    readiness_only: bool = False,
) -> Muscle:
    return Muscle(
        key=key,
        label=label,
        group=group,
        half_life_h=half_life_h,
        weekly_low=weekly_low,
        weekly_high=weekly_high,
        capacity_es=capacity_es,
        map_slug=key,
        region=region,
        parent=parent,
        legacy=legacy,
        deep=deep,
        readiness_only=readiness_only,
    )


