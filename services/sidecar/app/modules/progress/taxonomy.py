"""The 54 muscles and heads ASCEND tracks (taxonomy v2, docs/research/v8-anatomy.md).

v8 replaced the 19 coarse regions with the owner's list (pectoralis heads, three deltoids,
biceps and triceps heads, the four quadriceps, three hamstrings, glutes, core...) plus the
other trainable muscles the research pass kept (trapezius parts, rotator cuff, neck,
hip flexors, adductors, tibialis anterior, fibularis). Levator scapulae is folded into the
upper trapezius and coracobrachialis is left out (no exercise targets them on their own).
See ADR-0021.

half_life_h, weekly targets (effective sets per week, intermediate lifter) and capacity are
ESTIMATES for a fatigue model, not physiology measurements. Heads inherit their parent's
values (docs/research/v8-exercise-muscle-mapping.md §9). Small, deep or rarely loaded muscles
are readiness_only: they show recovery but never an "under-trained" or volume warning,
because no evidence supports weekly set targets for them.

`legacy` is the v7 region a muscle rolls up into (used by migration 0018 to translate old
hand-made weights and by its downgrade); "" means the muscle had no v7 region.
"""

